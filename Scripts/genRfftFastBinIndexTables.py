"""Generate the bin index tables of the indexed split stage of arm_rfft_fast_f32.

arm_cfft_f32 called with bitReverseFlag = 0 leaves frequency bin l of a
length-L transform at complex index armCfftBinIndexTable<L>[l] of its buffer.
Each table is derived from the library's own bit-reversal table
armBitRevIndexTable<L>: the swaps that arm_bitreversal_32 performs are applied
to an identity array, and entry l of the result is the index the bit-reversal
pass would have fetched bin l from.

The tables are written between marker comments in
Source/CommonTables/arm_common_tables.c and their declarations between marker
comments in Include/arm_common_tables.h. With --check nothing is written and
the exit status is 1 if either file differs from the generated content.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "Source" / "CommonTables" / "arm_common_tables.c"
HEADER = ROOT / "Include" / "arm_common_tables.h"
CFFT_LENGTHS = (16, 32, 64, 128, 256, 512, 1024, 2048)
MACRO = "ARM_MATH_RFFT_FAST_INDEXED_SPLIT"
# The tables are compiled only where the scalar arm_rfft_fast_f32 is.
GUARD = (
    f"defined({MACRO}) && !defined(ARM_MATH_NEON) \\\n"
    "    && !(defined(ARM_MATH_MVEF) && !defined(ARM_MATH_AUTOVECTORIZE))"
)
BEGIN = "/* BEGIN generated by Scripts/genRfftFastBinIndexTables.py; do not edit */\n"
END = "/* END generated by Scripts/genRfftFastBinIndexTables.py */\n"


def read_bitrev_table(source: str, length: int) -> list[int]:
    match = re.search(
        rf"const\s+uint16_t\s+armBitRevIndexTable{length}"
        rf"\[ARMBITREVINDEXTABLE_{length}_TABLE_LENGTH\][^=]*=\s*\{{(.*?)\}};",
        source,
        re.DOTALL,
    )
    if match is None:
        raise RuntimeError(f"cannot find armBitRevIndexTable{length} in {TABLES}")
    body = re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.DOTALL)
    values = [int(v) for v in re.findall(r"\d+", body)]
    declared = re.search(
        rf"#define\s+ARMBITREVINDEXTABLE_{length}_TABLE_LENGTH\s+\(\(uint16_t\)(\d+)\)",
        HEADER.read_text(encoding="utf-8-sig"),
    )
    if declared is None or int(declared.group(1)) != len(values):
        raise RuntimeError(f"armBitRevIndexTable{length}: length does not match the header")
    return values


def bin_index(bitrev: list[int], length: int) -> list[int]:
    # arm_bitreversal_32 on an identity array of 2 * length words: the table
    # holds byte offsets of the real parts of the complex pairs it exchanges.
    words = list(range(2 * length))
    for i in range(0, len(bitrev), 2):
        a = bitrev[i] >> 2
        b = bitrev[i + 1] >> 2
        words[a], words[b] = words[b], words[a]
        words[a + 1], words[b + 1] = words[b + 1], words[a + 1]
    index = [words[2 * l] >> 1 for l in range(length)]
    if any(words[2 * l + 1] != words[2 * l] + 1 or words[2 * l] & 1 for l in range(length)):
        raise RuntimeError(f"length {length}: the swaps do not keep complex pairs together")
    if sorted(index) != list(range(length)):
        raise RuntimeError(f"length {length}: not a permutation")
    return index


def render_tables(source: str) -> str:
    out = [BEGIN, f"#if {GUARD}\n"]
    for length in CFFT_LENGTHS:
        index = bin_index(read_bitrev_table(source, length), length)
        out.append(
            f"\nconst uint16_t armCfftBinIndexTable{length}[{length}] ARM_DSP_TABLE_ATTRIBUTE =\n{{\n"
        )
        rows = [index[i : i + 12] for i in range(0, length, 12)]
        out.append(",\n".join("   " + ", ".join(str(v) for v in row) for row in rows))
        out.append("\n};\n")
    out.append(f"\n#endif /* {MACRO}, scalar arm_rfft_fast_f32 */\n")
    out.append(END)
    return "".join(out)


def render_header() -> str:
    out = [
        "  " + BEGIN,
        "  /* Complex index, in the buffer arm_cfft_f32 leaves when called without bit\n"
        "     reversal, of each frequency bin. Defined only when\n"
        f"     {MACRO} is defined and the scalar\n"
        "     arm_rfft_fast_f32 is compiled (no Helium, no Neon). */\n",
    ]
    for length in CFFT_LENGTHS:
        out.append(f"    extern const uint16_t armCfftBinIndexTable{length}[{length}];\n")
    out.append("  " + END)
    return "".join(out)


def replace_block(text: str, block: str, path: Path) -> str:
    begin = block.split("\n", 1)[0] + "\n"
    end = block.rstrip("\n").rsplit("\n", 1)[1] + "\n"
    start = text.find(begin)
    stop = text.find(end)
    if start < 0 or stop < start:
        raise RuntimeError(f"generated-block markers not found in {path}")
    return text[:start] + block + text[stop + len(end) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="fail if the checked-in blocks differ")
    args = parser.parse_args()

    stale = []
    source = TABLES.read_text(encoding="utf-8-sig")
    for path, block in ((TABLES, render_tables(source)), (HEADER, render_header())):
        raw = path.read_bytes()
        bom = b"\xef\xbb\xbf" if raw.startswith(b"\xef\xbb\xbf") else b""
        text = raw[len(bom) :].decode("utf-8")
        updated = replace_block(text, block, path)
        if updated != text:
            if args.check:
                stale.append(path.relative_to(ROOT))
            else:
                path.write_bytes(bom + updated.encode("utf-8"))
    for path in stale:
        print(f"stale generated block: {path}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
